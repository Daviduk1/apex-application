  CREATE TABLE "FJ_JOBS" 
   (	"ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"TITLE" VARCHAR2(200) NOT NULL ENABLE, 
	"COMPANY_NAME" VARCHAR2(200), 
	"LOCATION" VARCHAR2(200), 
	"EMPLOYMENT_TYPE" VARCHAR2(50), 
	"SALARY_RANGE" VARCHAR2(50), 
	"SUBMISSION_DEADLINE" DATE, 
	"SECTOR" VARCHAR2(100), 
	"SUMMARY" VARCHAR2(1000), 
	"DESCRIPTION" VARCHAR2(4000), 
	"MIN_QUALIFICATION" VARCHAR2(100), 
	"EXPERIENCE_LEVEL" VARCHAR2(100), 
	"EXPERIENCE_LENGTH" VARCHAR2(100), 
	"REQUIREMENTS" VARCHAR2(4000), 
	"CREATED_AT" DATE DEFAULT sysdate NOT NULL ENABLE, 
	"UPDATED_AT" DATE DEFAULT sysdate NOT NULL ENABLE, 
	"IS_FILLED" VARCHAR2(1) DEFAULT 'N' NOT NULL ENABLE, 
	"FILLED_AT" DATE, 
	 PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FJ_JOBS_FILLED_CK" CHECK (is_filled in ('Y', 'N')) ENABLE
   ) ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "FJ_JOBS_BIU" 
before insert or update on fj_jobs
for each row
begin
  if inserting then
    :new.created_at := nvl(:new.created_at, sysdate);
  end if;
  if updating then
    :new.updated_at := sysdate;
  else
    :new.updated_at := nvl(:new.updated_at, sysdate);
  end if;
end;
/
ALTER TRIGGER "FJ_JOBS_BIU" ENABLE;